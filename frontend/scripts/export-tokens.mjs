export async function exportTokens({check=false}={}) {
  const css = await readFile(path.join(frontendRoot, tokenSource), 'utf8')
  const output = renderTokenList(css)
  const destination = path.join(frontendRoot, 'tokens.md')
  if (check) {
    const current = await readFile(destination, 'utf8').catch(()=>'')
    if (current.replaceAll('\r\n','\n') !== output) throw new Error('tokens.md 已过期；运行 npm run tokens:export 并提交更新。')
  } else await writeFile(destination, output)
  return output
}
if (process.argv[1] && path.resolve(process.argv[1])===fileURLToPath(import.meta.url)) {
  await exportTokens({check:process.argv.includes('--check')})
  console.log('Token 列表已'+(process.argv.includes('--check')?'验证':'导出')+'：frontend/tokens.md')
}
